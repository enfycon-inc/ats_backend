import type { SystemEmailRequest } from './system-email.types';

type Context = { workspace: string; recipient: string; fullName?: string };
export type WelcomeLoginOptions = {
  allowPasswordLogin: boolean;
  allowMicrosoftSso: boolean;
  allowGoogleSso: boolean;
};
export type SystemEmailTemplate = Context &
  (
    | {
        event: 'account_welcome';
        loginUrl: string;
        loginOptions: WelcomeLoginOptions;
        message?: string;
        role?: string;
        passwordSetupUrl?: string;
        temporaryPassword?: string;
      }
    | { event: 'registration_received' }
    | { event: 'workspace_activated'; loginUrl: string }
    | { event: 'role_approved'; loginUrl: string }
    | { event: 'team_invitation'; setupUrl: string; role?: string }
    | {
        event: 'account_created';
        loginUrl: string;
        role?: string;
        temporaryPassword?: string;
      }
    | { event: 'delivery_test' }
    | { event: 'password_reset_request'; resetUrl: string }
    | { event: 'password_changed_alert'; loginUrl?: string }
    | {
        event: 'admin_temp_password_notice';
        temporaryPassword: string;
        loginUrl: string;
      }
  );

const REPLY_MARKER = '<!--enfysync-reply-policy-->';
const DISCLAIMER =
  'This email was automatically generated by EnfySync. For assistance, contact your workspace administrator.';
export const escapeEmailText = (value: string) =>
  value.replace(
    /[&<>"']/g,
    (c) =>
      ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[
        c
      ]!,
  );

/** Application links only: no arbitrary origin, credentials, or executable schemes. */
export function applicationEmailUrl(value: string): string {
  const url = new URL(value);
  const configured = new URL(process.env.FRONTEND_URL || '');
  const base = process.env.BASE_DOMAIN?.toLowerCase();
  const local = ['localhost', '127.0.0.1'].includes(configured.hostname);
  const workspace =
    !!base &&
    url.hostname.endsWith('.' + base) &&
    /^[a-z0-9-]+$/.test(url.hostname.slice(0, -(base.length + 1)));
  if (
    url.username ||
    url.password ||
    !(
      url.origin === configured.origin ||
      (workspace && url.protocol === 'https:' && !url.port)
    ) ||
    (!local && url.protocol !== 'https:') ||
    !['https:', 'http:'].includes(url.protocol)
  ) {
    throw new Error('Invalid application email link.');
  }
  return url.toString();
}

export function workspaceEmailLogin(subdomain: string): string {
  const url = new URL('/auth/login', process.env.FRONTEND_URL || '');
  if (['localhost', '127.0.0.1'].includes(url.hostname))
    url.searchParams.set('subdomain', subdomain);
  else if (
    subdomain &&
    subdomain !== 'www' &&
    subdomain !== process.env.BASE_DOMAIN
  ) {
    if (!process.env.BASE_DOMAIN || !/^[a-z0-9-]+$/.test(subdomain))
      throw new Error('Invalid workspace email configuration.');
    url.hostname = `${subdomain}.${process.env.BASE_DOMAIN}`;
  }
  return applicationEmailUrl(url.toString());
}

export function renderSystemEmail(
  input: SystemEmailTemplate,
): Pick<SystemEmailRequest, 'subject' | 'html' | 'text' | 'systemGenerated'> {
  const details: [string, string][] = [['Workspace', input.workspace]];
  let title: string,
    preview: string,
    copy: string,
    action: { label: string; url: string } | undefined,
    note = '',
    welcomeInstructions = '';
  switch (input.event) {
    case 'account_welcome': {
      title = 'Welcome to your workspace';
      preview = `${input.fullName || 'Your account'} is ready at ${input.workspace}.`;
      copy = input.message || 'Your account is ready. You can now access your workspace.';
      details.push(
        ...(input.role ? ([['Role', input.role]] as [string, string][]) : []),
        ['Login email', input.recipient],
        ['Workspace URL', applicationEmailUrl(input.loginUrl)],
      );
      const providers = [
        ...(input.loginOptions.allowMicrosoftSso ? ['Microsoft'] : []),
        ...(input.loginOptions.allowGoogleSso ? ['Google'] : []),
      ];
      const passwordEnabled = input.loginOptions.allowPasswordLogin;
      const providerText = providers.length === 2 ? 'Microsoft or Google' : providers[0];
      if (providers.length && passwordEnabled) {
        welcomeInstructions = `Sign in with your corporate ${providerText} account, or set up your password to sign in with email and password.`;
      } else if (providers.length) {
        welcomeInstructions = `Sign in with your corporate ${providerText} account.`;
      } else if (passwordEnabled) {
        welcomeInstructions = 'Set up your password to sign in with your work email and password.';
      } else {
        welcomeInstructions = 'Contact your workspace administrator for help signing in.';
      }
      if (input.temporaryPassword && passwordEnabled) {
        details.push(['Temporary password', input.temporaryPassword]);
        note = 'Change your temporary password after your first sign in.';
      }
      if (input.passwordSetupUrl && passwordEnabled) {
        details.push(['Password setup', applicationEmailUrl(input.passwordSetupUrl)]);
      }
      action = { label: 'Open your workspace', url: input.loginUrl };
      break;
    }
    case 'registration_received':
      title = 'Your registration is received';
      preview = 'Your workspace is awaiting administrator approval.';
      copy =
        'We have received your workspace registration. Your account is pending administrator approval. We will email you when your workspace is ready.';
      details.push(['Status', 'Pending approval']);
      break;
    case 'workspace_activated':
      title = 'Your workspace is ready';
      preview = `${input.workspace} is active and ready to use.`;
      copy =
        'Your workspace is active. Sign in with your existing credentials to get started.';
      details.push(
        ['Status', 'Active'],
        ['Workspace URL', applicationEmailUrl(input.loginUrl)],
        ['Login email', input.recipient],
      );
      action = { label: 'Open your workspace', url: input.loginUrl };
      break;
    case 'role_approved':
      title = 'Your access request was approved';
      preview = `Your access request for ${input.workspace} was approved.`;
      copy =
        'Your request to join this workspace has been approved. Sign in with your existing credentials to get started.';
      details.push(
        ['Status', 'Approved'],
        ['Login email', input.recipient],
        ['Workspace URL', applicationEmailUrl(input.loginUrl)],
      );
      action = { label: 'Sign in to your workspace', url: input.loginUrl };
      break;
    case 'team_invitation':
      title = 'Join your team on EnfySync';
      preview = `You have been invited to join ${input.workspace}.`;
      copy =
        'You have been invited to join your team. Set up your account using the secure invitation link below.';
      details.push(
        ['Role', input.role || 'Team Member'],
        ['Login email', input.recipient],
        ['Invitation', 'Valid for 24 hours'],
      );
      action = { label: 'Set up your account', url: input.setupUrl };
      note =
        'If you did not expect this invitation, contact your workspace administrator.';
      break;
    case 'account_created':
      title = 'Your account is ready';
      preview = `Your account has been created for ${input.workspace}.`;
      copy =
        'Your workspace account has been created. Use your account credentials to sign in.';
      details.push(
        ['Role', input.role || 'Team Member'],
        ['Login email', input.recipient],
        ['Workspace URL', applicationEmailUrl(input.loginUrl)],
      );
      if (input.temporaryPassword) {
        details.push(['Password', input.temporaryPassword]);
        note =
          'Keep your account credentials private. Never forward this email.';
      }
      action = { label: 'Sign in to your workspace', url: input.loginUrl };
      break;
    case 'delivery_test':
      title = 'Email delivery test';
      preview = 'Check receipt from your selected workspace email sender.';
      copy =
        'This message tests your selected workspace system email sender. If you are reading it, this test reached your inbox.';
      details.push(['Purpose', 'System email verification']);
      note = 'This test does not guarantee delivery of future messages.';
      break;
    case 'password_reset_request':
      title = 'Reset your password';
      preview = `Password reset request for ${input.workspace}.`;
      copy =
        'We received a request to reset your password. Use the secure link below to choose a new password. For security, this link expires in 30 minutes.';
      details.push(
        ['Account email', input.recipient],
        ['Link expiry', 'Valid for 30 minutes'],
      );
      action = { label: 'Reset My Password', url: input.resetUrl };
      note =
        'If you did not request a password reset, no further action is required. Your password will remain unchanged.';
      break;
    case 'password_changed_alert':
      title = 'Password successfully changed';
      preview = `Security alert: Your password for ${input.workspace} was updated.`;
      copy =
        'The password for your EnfySync account was successfully updated. You can now use your new password to sign in.';
      details.push(
        ['Account email', input.recipient],
        ['Status', 'Password changed'],
      );
      if (input.loginUrl) {
        action = { label: 'Sign in to workspace', url: input.loginUrl };
      }
      note =
        'If you did not perform this change, please immediately contact your workspace administrator or support.';
      break;
    case 'admin_temp_password_notice':
      title = 'Your password was reset';
      preview = `An administrator updated your password for ${input.workspace}.`;
      copy =
        'Your workspace administrator has reset your password and assigned a temporary credential. Sign in and change your password immediately.';
      details.push(
        ['Account email', input.recipient],
        ['Temporary password', input.temporaryPassword],
        ['Workspace URL', applicationEmailUrl(input.loginUrl)],
      );
      action = { label: 'Sign in to workspace', url: input.loginUrl };
      note =
        'Keep your account credentials confidential. Please change your password upon signing in.';
      break;
  }
  const subject = {
    registration_received: 'Registration received',
    workspace_activated: 'Your workspace is ready',
    role_approved: 'Your access request was approved',
    team_invitation: 'Invitation to join',
    account_created: 'Your account is ready',
    account_welcome: 'Welcome to your workspace',
    delivery_test: 'Email delivery test',
    password_reset_request: 'Reset your password',
    password_changed_alert: 'Security Alert: Password updated',
    admin_temp_password_notice: 'Your password was reset by administrator',
  }[input.event];
  const safeSubject =
    `EnfySync — ${subject}${input.event === 'delivery_test' ? '' : ' · ' + input.workspace}`.replace(
      /[\r\n]/g,
      ' ',
    );
  const e = escapeEmailText;
  const rows = details
    .map(
      ([label, value]) =>
        `<tr><td style="padding:10px 12px;border-bottom:1px solid #e2e8f0;color:#475569;vertical-align:top;width:34%">${e(label)}</td><td style="padding:10px 12px;border-bottom:1px solid #e2e8f0;color:#0f172a;word-break:break-word">${e(value)}</td></tr>`,
    )
    .join('');
  const url = action ? applicationEmailUrl(action.url) : undefined;
  const button =
    action && url
      ? `<table role="presentation" cellpadding="0" cellspacing="0" style="margin:24px 0 16px"><tr><td bgcolor="#1e4e98" style="border-radius:4px;mso-padding-alt:14px 24px"><a href="${e(url)}" style="display:inline-block;padding:14px 24px;font-size:15px;font-weight:bold;color:#ffffff;text-decoration:none">${e(action.label)}</a></td></tr></table><p style="font-size:12px;color:#475569;word-break:break-all">Or copy and open this link:<br><a href="${e(url)}" style="color:#1e4e98">${e(url)}</a></p>`
      : '';
  const setupButton = input.event === 'account_welcome' && input.passwordSetupUrl
    ? `<p style="margin:12px 0"><a href="${e(applicationEmailUrl(input.passwordSetupUrl))}" style="color:#1e4e98;font-weight:bold">Set up your password</a></p>`
    : '';
  const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${e(title)}</title></head><body style="margin:0;background:#f1f5f9;font-family:Arial,Helvetica,sans-serif;color:#0f172a"><div style="display:none;font-size:1px;line-height:1px;max-height:0;max-width:0;opacity:0;overflow:hidden;mso-hide:all">${e(preview)}</div><table role="presentation" width="100%" cellpadding="0" cellspacing="0" bgcolor="#f1f5f9"><tr><td align="center" style="padding:24px 12px"><table role="presentation" width="600" cellpadding="0" cellspacing="0" style="width:100%;max-width:600px;background:#ffffff;border:1px solid #e2e8f0;border-top:4px solid #1e4e98"><tr><td style="padding:28px 24px 12px"><span style="font-size:25px;font-weight:bold;color:#1e4e98">EnfySync</span><br><span style="font-size:10px;letter-spacing:1px;color:#64748b">AI RECRUITMENT</span></td></tr><tr><td style="padding:12px 24px 28px;font-size:15px;line-height:1.6"><h1 style="font-size:24px;line-height:1.3;margin:0 0 20px">${e(title)}</h1><p>Hi ${e(input.fullName || 'there')},</p><p>${e(copy)}</p>${welcomeInstructions ? `<p>${e(welcomeInstructions)}</p>` : ''}<table role="presentation" width="100%" cellpadding="0" cellspacing="0" bgcolor="#f8fafc" style="border:1px solid #e2e8f0;font-size:14px;margin:20px 0">${rows}</table>${button}${setupButton}${note ? `<p style="font-size:13px;color:#475569">${e(note)}</p>` : ''}</td></tr><tr><td style="padding:20px 24px;border-top:1px solid #e2e8f0;font-size:12px;line-height:1.6;color:#64748b"><strong style="color:#1e4e98">EnfySync AI Recruitment Platform</strong><br>${e(input.workspace)}<p style="margin:10px 0">${DISCLAIMER}${REPLY_MARKER}</p><span>© ${new Date().getFullYear()} EnfySync</span></td></tr></table></td></tr></table></body></html>`;
  const text = [
    title,
    `Hi ${input.fullName || 'there'},`,
    copy,
    welcomeInstructions,
    ...details.map(([label, value]) => `${label}: ${value}`),
    ...(action && url ? [action.label + ': ' + url] : []),
    ...(input.event === 'account_welcome' && input.passwordSetupUrl
      ? ['Set up your password: ' + applicationEmailUrl(input.passwordSetupUrl)]
      : []),
    note,
    'EnfySync AI Recruitment Platform',
    input.workspace,
    DISCLAIMER,
    `© ${new Date().getFullYear()} EnfySync`,
  ]
    .filter(Boolean)
    .join('\n\n');
  return { subject: safeSubject, html, text, systemGenerated: true };
}

/** Evaluated using the actual sending account, rather than assuming platform mail. */
export function applySystemEmailReplyPolicy(
  request: SystemEmailRequest,
  from: string,
): SystemEmailRequest {
  if (!request.systemGenerated) return request;
  const noReply = /^(no-?reply)@/i.test(from) && !request.replyTo;
  return {
    ...request,
    html: request.html.replace(
      REPLY_MARKER,
      noReply ? '<br>Please do not reply to this email.' : '',
    ),
    text: request.text
      ? request.text + (noReply ? '\n\nPlease do not reply to this email.' : '')
      : undefined,
  };
}
