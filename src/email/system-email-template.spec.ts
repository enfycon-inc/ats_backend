import {
  applicationEmailUrl,
  applySystemEmailReplyPolicy,
  renderSystemEmail,
  workspaceEmailLogin,
  SystemEmailTemplate,
} from './system-email-template';

describe('corporate system email templates', () => {
  const env = { ...process.env };
  beforeEach(() => {
    process.env.FRONTEND_URL = 'https://enfyjobs.com';
    process.env.BASE_DOMAIN = 'enfyjobs.com';
  });
  afterEach(() => {
    process.env = { ...env };
  });
  const context = {
    workspace: 'Deb <script>bad</script>',
    recipient: 'user@example.com',
    fullName: '<img src=x onerror=alert(1)>',
  };
  const variants: SystemEmailTemplate[] = [
    {
      ...context,
      event: 'account_welcome',
      loginUrl: 'https://deb.enfyjobs.com/auth/login',
      loginOptions: { allowPasswordLogin: true, allowMicrosoftSso: true, allowGoogleSso: true },
      passwordSetupUrl: 'https://enfyjobs.com/auth/setup-password?token=abc',
      role: 'Recruiter',
      branch: 'Enfycon',
      unit: 'India Staffing',
    },
    { ...context, event: 'registration_received' },
    {
      ...context,
      event: 'workspace_activated',
      loginUrl: 'https://deb.enfyjobs.com/auth/login',
    },
    {
      ...context,
      event: 'team_invitation',
      setupUrl: 'https://enfyjobs.com/auth/setup-password?token=abc%26def',
      role: 'Recruiter',
    },
    {
      ...context,
      event: 'account_created',
      loginUrl: 'https://deb.enfyjobs.com/auth/login',
    },
    { ...context, event: 'delivery_test' },
    {
      ...context,
      event: 'role_approved',
      loginUrl: 'https://deb.enfyjobs.com/auth/login',
    },
    {
      ...context,
      event: 'pod_lead_assigned',
      podName: 'POD(Backend)',
      branch: 'Kolkata',
      unit: 'India Staffing',
      loginUrl: 'https://deb.enfyjobs.com/auth/login',
    },
    {
      ...context,
      event: 'role_changed_alert',
      newRoles: 'Delivery Head',
      previousRoles: 'Recruiter',
      branch: 'Kolkata',
      unit: 'India Staffing',
      loginUrl: 'https://deb.enfyjobs.com/auth/login',
    },
  ];
  it.each(variants)(
    'renders escaped $event content with common branding and disclaimer',
    (input) => {
      const content = renderSystemEmail(input);
      expect(content.html).not.toContain('<script>');
      expect(content.html).not.toContain('<img src=x');
      expect(content.html).toContain('&lt;script&gt;');
      expect(content.html).toContain(
        'This email was automatically generated by EnfySync.',
      );
      expect(content.html).toContain('helpdesk@enfycon.com');
      expect(content.text).toContain(
        'This email was automatically generated by EnfySync.',
      );
      expect(content.text).toContain('helpdesk@enfycon.com');
      expect(content.subject).toMatch(/^EnfySync — /);
      const delivered = applySystemEmailReplyPolicy(
        { tenantId: 'a', to: context.recipient, ...content },
        'no-reply@enfyjobs.com',
      );
      expect(delivered.html).not.toContain('<!--enfysync-reply-policy-->');
      expect(delivered.html).toContain('Please do not reply to this email.');
      expect(delivered.text).toContain('Please do not reply to this email.');
    },
  );
  it('does not discourage replies to configured tenant accounts or explicit reply-to', () => {
    const request = {
      tenantId: 'a',
      to: context.recipient,
      ...renderSystemEmail(variants[0]),
    };
    for (const [from, replyTo] of [
      ['hr@example.com', undefined],
      ['no-reply@enfyjobs.com', 'admin@example.com'],
    ]) {
      const result = applySystemEmailReplyPolicy(
        { ...request, replyTo },
        from!,
      );
      expect(result.html).not.toContain('Please do not reply');
      expect(result.text).not.toContain('Please do not reply');
    }
  });
  it('has no pending login action and no universal social sign-in claims', () => {
    expect(renderSystemEmail(variants[1]).html).not.toContain(
      'Open your workspace',
    );
    const invite = renderSystemEmail(variants[3]);
    expect(invite.html).toContain('Valid for 24 hours');
    expect(invite.html).not.toContain('Sign in with Google');
    expect(invite.html).toContain('token=abc%26def');
  });
  it('renders only the login methods enabled for the tenant', () => {
    const render = (loginOptions: Extract<SystemEmailTemplate, { event: 'account_welcome' }>['loginOptions']) =>
      renderSystemEmail({
        ...context,
        event: 'account_welcome',
        loginUrl: 'https://deb.enfyjobs.com/auth/login',
        loginOptions,
        passwordSetupUrl: 'https://enfyjobs.com/auth/setup-password?token=abc',
      });
    expect(render({ allowPasswordLogin: true, allowMicrosoftSso: true, allowGoogleSso: true }).text)
      .toContain('Microsoft or Google account, or set up your password');
    expect(render({ allowPasswordLogin: true, allowMicrosoftSso: true, allowGoogleSso: false }).text)
      .toContain('corporate Microsoft account, or set up your password');
    expect(render({ allowPasswordLogin: false, allowMicrosoftSso: true, allowGoogleSso: false }).text)
      .toContain('choose Microsoft to sign in with your corporate account');
    expect(render({ allowPasswordLogin: false, allowMicrosoftSso: true, allowGoogleSso: false }).text)
      .not.toContain('Google');
    expect(render({ allowPasswordLogin: false, allowMicrosoftSso: true, allowGoogleSso: false }).html)
      .not.toContain('setup-password');
    expect(render({ allowPasswordLogin: false, allowMicrosoftSso: true, allowGoogleSso: false }).text)
      .not.toContain('setup-password');
  });
  it('includes role in welcome details when provided and aligns both welcome actions to the same width', () => {
    const email = renderSystemEmail(variants[0]);
    expect(email.text).toContain('Branch: Enfycon');
    expect(email.text).toContain('Unit: India Staffing');
    expect(email.text).toContain('Role: Recruiter');
    expect(email.html).toContain('>Role<');
    expect(email.html).toContain('>Recruiter<');
    const fullWidthCenteredAction = 'display:block;box-sizing:border-box;width:100%;';
    expect(email.html.match(new RegExp(fullWidthCenteredAction, 'g'))).toHaveLength(2);
  });
  it('renders pod lead assigned notification with pod details and login action', () => {
    const email = renderSystemEmail({
      ...context,
      event: 'pod_lead_assigned',
      podName: 'POD(Backend)',
      branch: 'Kolkata',
      unit: 'India Staffing',
      loginUrl: 'https://deb.enfyjobs.com/auth/login',
    });
    expect(email.subject).toContain('Assigned as Pod Lead');
    expect(email.html).toContain('Assigned as Pod Lead');
    expect(email.html).toContain('POD(Backend)');
    expect(email.html).toContain('India Staffing');
    expect(email.html).toContain('Kolkata');
    expect(email.html).toContain('Open your workspace');
    expect(email.text).toContain('Pod name: POD(Backend)');
    expect(email.text).toContain('helpdesk@enfycon.com');
  });
  it('renders role changed alert with new and previous roles', () => {
    const email = renderSystemEmail({
      ...context,
      event: 'role_changed_alert',
      newRoles: 'Delivery Head',
      previousRoles: 'Recruiter',
      branch: 'Kolkata',
      unit: 'India Staffing',
      loginUrl: 'https://deb.enfyjobs.com/auth/login',
    });
    expect(email.subject).toContain('Role update notification');
    expect(email.html).toContain('Delivery Head');
    expect(email.html).toContain('Recruiter');
    expect(email.text).toContain('New role: Delivery Head');
    expect(email.text).toContain('Previous role: Recruiter');
    expect(email.text).toContain('helpdesk@enfycon.com');
  });
  it('renders role approval with a validated workspace login link and existing-credentials guidance', () => {
    const email = renderSystemEmail({
      ...context,
      event: 'role_approved',
      loginUrl: 'https://deb.enfyjobs.com/auth/login',
    });
    expect(email.subject).toContain('Your access request was approved');
    expect(email.html).toContain('approved');
    expect(email.html).toContain('existing credentials');
    expect(email.html).toContain('https://deb.enfyjobs.com/auth/login');
    expect(email.text).toContain('Sign in with your existing credentials');
  });
  it('preserves optional credential instructions, escaping HTML and sanitizing subject newlines', () => {
    const email = renderSystemEmail({
      ...context,
      workspace: 'Deb\r\nBcc: wrong@example.com',
      event: 'account_created',
      loginUrl: 'https://deb.enfyjobs.com/auth/login',
      temporaryPassword: '<secret>',
    });
    expect(email.html).toContain('&lt;secret&gt;');
    expect(email.text).toContain('Password: <secret>');
    expect(email.subject).not.toMatch(/[\r\n]/);
    expect(renderSystemEmail(variants[3]).html).not.toContain('>Password<');
  });
  it.each([
    'javascript:alert(1)',
    'https://evil.example/auth/login',
    'https://enfyjobs.com.evil.example',
    'https://user:password@enfyjobs.com',
    'https://nested.deb.enfyjobs.com',
    'http://enfyjobs.com',
  ])('rejects unsafe action URL %s', (url) => {
    expect(() => applicationEmailUrl(url)).toThrow();
  });
  it('supports trusted workspace and local URLs without deceptive subdomains', () => {
    expect(workspaceEmailLogin('deb')).toBe(
      'https://deb.enfyjobs.com/auth/login',
    );
    expect(() => workspaceEmailLogin('deb.evil')).toThrow();
    process.env.FRONTEND_URL = 'http://localhost:3000';
    expect(workspaceEmailLogin('deb')).toBe(
      'http://localhost:3000/auth/login?subdomain=deb',
    );
  });

  it.each([
    ['role_changed_alert', 'Updated', { newRoles: 'Recruiter', loginUrl: 'https://deb.enfyjobs.com/auth/login' }],
    ['pod_lead_assigned', 'Assigned', { podName: 'India', loginUrl: 'https://deb.enfyjobs.com/auth/login' }],
    ['admin_temp_password_notice', 'Updated', { temporaryPassword: 'temporary', loginUrl: 'https://deb.enfyjobs.com/auth/login' }],
    ['password_changed_alert', 'Updated', {}],
    ['workspace_activated', 'Activated', { loginUrl: 'https://deb.enfyjobs.com/auth/login' }],
    ['team_invitation', 'Invited', { setupUrl: 'https://deb.enfyjobs.com/auth/setup-password?token=sample' }],
    ['account_created', 'Created', { loginUrl: 'https://deb.enfyjobs.com/auth/login' }],
    ['delivery_test', 'Sent', {}],
  ])('attributes %s with name in prose and combined identity in one row', (event, action, extra) => {
    const rendered = renderSystemEmail({ ...context, event, ...extra, actor: { fullName: 'Sahadeb Barman', email: 'actor@example.com' } } as SystemEmailTemplate);
    expect(rendered.html).toContain('by <strong>Sahadeb Barman</strong>');
    expect(rendered.text).toContain(`${action} by: Sahadeb Barman (actor@example.com)`);
    const prose = rendered.html.match(/<p>Hi .*?<\/p><p>(.*?)<\/p>/)?.[1];
    expect(prose).not.toContain('actor@example.com');
  });
  it('escapes actor markup and uses email alone when a display name is unavailable', () => {
    const base = { ...context, event: 'role_changed_alert' as const, newRoles: 'Recruiter', loginUrl: 'https://deb.enfyjobs.com/auth/login' };
    const rendered = renderSystemEmail({ ...base, actor: { fullName: '<script>actor</script>', email: 'actor@example.com' } });
    expect(rendered.html).not.toContain('<script>actor</script>');
    expect(rendered.html).toContain('&lt;script&gt;actor&lt;/script&gt; (actor@example.com)');
    expect(renderSystemEmail({ ...base, actor: { fullName: ' ', email: 'actor@example.com' } }).text).toContain('Updated by: actor@example.com');
  });
  it('does not invent an updater for automatic registration messages', () => {
    expect(renderSystemEmail({ ...context, event: 'registration_received' }).text).not.toMatch(/Updated by:|Created by:|Activated by:/);
  });
});
